const FULLWIDTH_START = 0xff01;
const FULLWIDTH_END = 0xff5e;

function fullwidthToHalfwidth(ch: string): string {
  const code = ch.codePointAt(0)!;
  if (code === 0x3000) return " "; // 全角空格
  if (code >= FULLWIDTH_START && code <= FULLWIDTH_END) {
    return String.fromCodePoint(code - 0xfee0);
  }
  return ch;
}

// 匹配空白与常见中英文标点（含全角）。
const PUNCT_AND_SPACE =
  /[\s　、。！-／：-＠［-｀｛-～‘’“”…—【】《》〈〉「」『』（）.,!?;:'"()[\]{}<>_\-~`@#$%^&*+=|\/]/g;

export function normalize(s: string): string {
  if (!s) return "";
  const noPunctSpace = s.replace(PUNCT_AND_SPACE, "");
  let result = "";
  for (const ch of noPunctSpace) {
    const half = fullwidthToHalfwidth(ch);
    result += TRAD_TO_SIMP[half] ?? half;
  }
  return result;
}
